import type { HistoryTopicDef } from '../model/types.ts';

/* ---------------------------------------------------------------------------
   History topics. A tree of what a learner can ask about, with phrasings in
   each language that map a free-text question to a topic. Cases attach
   facts to topics; a topic the case says nothing about answers with its
   natural default, so asking about something irrelevant gets an ordinary
   reply and never "this is not part of the case".

   The matcher is deliberately simple (see engine/history.ts); an LLM can
   later replace the matching without changing this data.
--------------------------------------------------------------------------- */

