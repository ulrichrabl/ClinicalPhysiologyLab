/* Write docs/knowledge-coverage.md: every sign with its definition, the tests that elicit it, where the app shows it,
   which cases show it and what the model cannot show yet (ADR-016 §12). Generated from the knowledge tables and the
   running models; regenerate after changing either: npm run knowledge:report */
import * as esbuild from '../node_modules/esbuild/lib/main.js';
import { writeFileSync, unlinkSync } from 'node:fs';
import { join } from 'node:path';
import { tmpdir } from 'node:os';
import { pathToFileURL } from 'node:url';

const bundle = join(tmpdir(), `knowledge-report-${Date.now()}.mjs`);
await esbuild.build({ entryPoints: ['scripts/_vp_entry.ts'], bundle: true, outfile: bundle, format: 'esm', target: 'es2022', platform: 'node',
  loader: { '.ts': 'ts', '.js': 'js', '.json': 'json' }, logLevel: 'error' });
const vp = await import(pathToFileURL(bundle).href);
unlinkSync(bundle);
const { CATALOG, REGISTRY, CASES, KNOWLEDGE, observe, buildView, modelFromCase, settleModel, chemistryState, signsOf, syndromePresent, syndromeSigns,
  coverage, coverageSummary, labelOf } = vp;

const per = {};
for (const c of CASES) {
  const m = modelFromCase(c); const snap = settleModel(m, 16).snapshot;
  const v = buildView(c, { circulation: snap, chemistry: chemistryState(snap, m.chemistry), state: { ...c.initialState, exposure: ['chest', 'arm', 'neck', 'abdomen', 'legs'] } });
  per[c.id] = signsOf(KNOWLEDGE, CATALOG, (ref, ctx) => observe(CATALOG, REGISTRY.resolvers, c, v, ref, ctx));
}
const rows = coverage(KNOWLEDGE, CATALOG, per);
const cell = (s) => String(s ?? '').replace(/\|/g, '\\|').replace(/\n/g, ' ');
const code = (s) => '`' + s + '`';

function def(d) {
  if (!d) return '—';
  if (d.all) return d.all.map(def).join(' and ');
  if (d.any) return d.any.map(def).join(' or ');
  if (d.not) return `not (${def(d.not)})`;
  if (d.fn) return code(`${d.fn}(${d.args ? Object.entries(d.args).map(([k, v]) => `${k}=${JSON.stringify(v)}`).join(', ') : ''})`);
  const v = d.value === undefined ? '' : ' ' + JSON.stringify(d.value);
  return code(`${d.obs}${d.path ? '.' + d.path : ''} ${d.op}${v}`) + (d.ctx ? ` in ${code(JSON.stringify(d.ctx))}` : '') + (d.side && d.side !== 'any' ? ` (${d.side} side)` : '');
}

const SITES = [
  ['Vital signs', ['vitals']], ['General inspection, skin and hands', ['general', 'skin', 'hands']], ['Eyes', ['eye']], ['Mouth, breath and neck', ['mouth', 'breath', 'neck']],
  ['Pulse and heart', ['pulse', 'heart']], ['Chest and lungs', ['chest']], ['Abdomen and rectum', ['abdomen', 'rectum']], ['Legs', ['limb.lower']],
  ['Hearing', ['ear', 'head']], ['Stance and gait', ['posture', 'gait']], ['Face and cranial nerves', ['face']], ['Speech', ['speech']],
  ['Limbs: motor, coordination, sensory', ['limb', 'limb.upper', 'trunk', 'perineum']], ['ECG (read from the tracing, ADR-017)', ['ecg']],
];
const L = [];
const w = (s = '') => L.push(s);
w('# Knowledge coverage');
w();
w('Generated by `npm run knowledge:report` from `source/knowledge/` and the running models (ADR-016 §12). Do not edit by hand.');
w();
w('## Summary');
w();
for (const l of coverageSummary(rows)) w(`- ${l}.`);
w();
w('**Representation:** *model*, the models produce the observables the definition reads; *case layer only*, only a case can author them; *needs an intervention*, deciding it needs, for example, oxygen to be given; *not represented*, no observable yet.');
w();
w('**Elicited by** is derived: the tests that reveal an observable the sign reads, in a context its definition allows. An intervention listed first (a position) is the step before.');
w();
for (const [title, sites] of SITES) {
  const rs = rows.filter((r) => sites.includes(KNOWLEDGE.signs[r.id].site));
  if (!rs.length) continue;
  w(`## ${title}`);
  w();
  w('| Sign | Definition | Elicited by | Shown by | Cases | Gap |');
  w('|---|---|---|---|---|---|');
  for (const r of rs) {
    const s = KNOWLEDGE.signs[r.id];
    const name = `**${cell(labelOf(KNOWLEDGE, `sign:${r.id}`, 'en'))}**<br>${cell(labelOf(KNOWLEDGE, `sign:${r.id}`, 'de'))}<br>${code(r.id)}${s.normalVariant ? ' · normal variant' : ''}`;
    const thr = s.threshold ? `<br>Threshold: ${cell(s.threshold.text)} (${s.threshold.status})` : '';
    const rep = r.representation === 'model' ? '' : `<br>*${r.representation}*`;
    w(`| ${name} | ${def(s.definition)}${thr}${rep} | ${r.tests.map(code).join(', ') || '—'} | ${r.channels.join(', ') || '—'} | ${r.cases.join(', ') || '—'} | ${cell(s.modelGap ?? '')} |`);
  }
  w();
}
w('## Syndromes');
w();
w('A syndrome is present when every required sign is present, every pertinent negative absent, and, without a required sign, at least two supporting signs are present.');
w();
w('| Syndrome | Signs | Cases |');
w('|---|---|---|');
for (const id of Object.keys(KNOWLEDGE.syndromes)) {
  const ms = syndromeSigns(KNOWLEDGE, id).map((m) => code(m.sign) + (m.role === 'supporting' ? '' : ` (${m.role})`)).join(', ');
  const cs = CASES.filter((c) => syndromePresent(KNOWLEDGE, id, per[c.id])).map((c) => c.id).join(', ');
  w(`| **${cell(labelOf(KNOWLEDGE, `syndrome:${id}`, 'en'))}**<br>${cell(labelOf(KNOWLEDGE, `syndrome:${id}`, 'de'))} | ${ms} | ${cs || '—'} |`);
}
w();
w('## Where a case does not show a linked sign');
w();
w('Each `suggests` link to a condition with a case must show in that case, or carry an exception: *model* when the model cannot produce it yet, *case* when this patient rightly does not have it.');
w();
w('| Link | Case | Kind | Why |');
w('|---|---|---|---|');
for (const r of KNOWLEDGE.relations.filter((x) => x.rel === 'suggests' && x.exceptions)) {
  for (const x of r.exceptions) w(`| ${code(r.from)} → ${code(r.to.slice('condition:'.length))} | ${x.case} | ${x.kind} | ${cell(x.why)} |`);
}
w();
writeFileSync('../docs/knowledge-coverage.md', L.join('\n'));
console.log(`docs/knowledge-coverage.md: ${rows.length} signs`);
